def set_language(language):
    global _language
    _language = language


def tr(source):
    if _language == "ru":
        return _RUSSIAN.get(source, source)
    return source


def translated(widget, source, setter="setText"):
    bindings = getattr(widget, "_translation_bindings", {})
    bindings[setter] = source
    widget._translation_bindings = bindings
    _apply_translation(widget, setter, source)
    return widget


def translated_action(menu, source, *args):
    return translated(menu.addAction(source, *args), source)


def _apply_translation(widget, setter, source):
    if setter == "items":
        for index, caption in enumerate(source):
            widget.setItemText(index, tr(caption))
    elif setter == "setHorizontalHeaderLabels":
        widget.setHorizontalHeaderLabels([tr(caption) for caption in source])
    else:
        getattr(widget, setter)(tr(source))


def retranslate(root):
    from PySide6.QtCore import QObject

    for widget in root.findChildren(QObject):
        for setter, source in getattr(widget, "_translation_bindings", {}).items():
            _apply_translation(widget, setter, source)
